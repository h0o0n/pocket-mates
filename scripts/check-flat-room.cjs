// Install Playwright or point PLAYWRIGHT_MODULE to an existing installation.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:process.env.TEST_BROWSER_CHANNEL || 'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:1000}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5180/');
 await page.locator('.mochi-breathe img').first().waitFor();
 await page.evaluate(()=>document.fonts.ready);
 await page.locator('.flat-time button').filter({hasText:'낮'}).click();
 fs.mkdirSync('output/flat-room',{recursive:true});
 await page.locator('.flat-room').first().screenshot({path:'output/flat-room/day.png'});
 assert.equal(await page.locator('.flat-room:not(.miniature) .dog-receipt').count(),0);
 assert.equal(await page.locator('.flat-room:not(.miniature) .dog-sunglasses').count(),0);
 await page.locator('.flat-time button').filter({hasText:'밤'}).click();
 await page.waitForTimeout(2200);
 await page.locator('.flat-room').first().screenshot({path:'output/flat-room/night.png'});
 await page.getByRole('button',{name:'내 아이템',exact:true}).click();
 await page.locator('.zone-filters button').filter({hasText:'바닥'}).click();
 const sofa=page.locator('.decoration-grid article').filter({hasText:'남색 소파'});
 await sofa.getByRole('button',{name:'방에서 치우기'}).click();
 assert.equal(await page.locator('.flat-room:not(.miniature) .prop-furniture-sofa').count(),0);
 await page.reload();
 assert.equal(await page.locator('.flat-room:not(.miniature) .prop-furniture-sofa').count(),0);
 await page.getByRole('button',{name:'소품 상점',exact:true}).click();
 await page.locator('.zone-filters button').filter({hasText:'벽'}).click();
 const clock=page.locator('.decoration-grid article').filter({hasText:'레트로 벽시계'});
 await clock.getByRole('button').click();
 assert.equal(await clock.count(),0);
 await page.getByRole('button',{name:'내 아이템',exact:true}).click();
 assert.equal(await page.locator('.decoration-grid article').filter({hasText:'레트로 벽시계'}).count(),1);
 await page.evaluate(()=>{ const now=new Date().toISOString(); const expenses=Array.from({length:24},(_,i)=>({id:`test-${i}`,memo:'검증',category:i<12?'delivery':'shopping',amount:60000,spentAt:now})); localStorage.setItem('pocket-expenses',JSON.stringify(expenses)); });
 await page.reload();
 assert.equal(await page.locator('.flat-room:not(.miniature) .flat-clutter').count(),8);
 assert.equal(await page.locator('.flat-room:not(.miniature) .wear-marks').count(),1);
 assert.equal(await page.locator('.flat-room:not(.miniature) .dog-receipt').count(),1);
 assert.equal(await page.locator('.flat-room:not(.miniature) .dog-sunglasses').count(),1);
 assert.equal(await page.locator('.flat-room:not(.miniature) .belly-2').count(),1);
 await page.locator('.flat-room').first().screenshot({path:'output/flat-room/reactions.png'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('.flat-time button').filter({hasText:'노을'}).click();
 await page.waitForTimeout(2200);
 await page.screenshot({path:'output/flat-room/mobile.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.getByRole('button',{name:'강아지와 대화하기',exact:true}).first().click();
 assert.equal(await page.locator('.mochi-speech').count(),1);
 await page.evaluate(()=>localStorage.setItem('pocket-expenses','[]'));
 await page.reload();
 assert.equal(await page.locator('.flat-room:not(.miniature) .dog-receipt').count(),0);
 assert.equal(await page.locator('.flat-room:not(.miniature) .dog-sunglasses').count(),0);
 assert.equal(await page.locator('.flat-room:not(.miniature) .dog-belly').count(),0);
 await page.evaluate(()=>{
   const layouts=JSON.parse(localStorage.getItem('pocket-flat-layouts-v1'));
   for(const key of Object.keys(layouts)) layouts[key]=[...layouts[key].filter(id=>id!=='floor-lamp'),'christmas-tree'];
   localStorage.setItem('pocket-flat-layouts-v1',JSON.stringify(layouts));
 });
 await page.reload();
 const tree=page.locator('.flat-room:not(.miniature) .prop-christmas-tree');
 assert.equal(await tree.locator('svg').getAttribute('preserveAspectRatio'),'xMidYMax meet');
 const mobileTree=await tree.boundingBox();
 assert.ok(Math.abs(mobileTree.width/mobileTree.height-150/170)<.02);
 await page.locator('.flat-room').first().screenshot({path:'output/flat-room/tree-mobile.png'});
 await page.setViewportSize({width:1280,height:1000});
 const desktopTree=await tree.boundingBox();
 assert.ok(Math.abs(desktopTree.width/desktopTree.height-150/170)<.02);
 await page.locator('.flat-room').first().screenshot({path:'output/flat-room/tree-desktop.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: day/night, remove persistence, shop/inventory transfer, clutter cap, wear, mobile overflow, dog interaction');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
